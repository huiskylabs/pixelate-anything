EYE_KEY = {'d': 'wood0', 'x': 'ol', 'X': 'wh', 'I': 'gold2', 'i': 'ol', 'w': 'wood1'}


def stump():
    base = grid_from(STUMP, STUMP_KEY)
    frames = []
    for e in EYES:
        g = copy(base)
        for j, row in enumerate(e):
            for i, c in enumerate(row):
                if c != '.':
                    g.a[8 + j][5 + i] = EYE_KEY[c]
        frames.append(g)
    return frames


