def snail():
    out = grid_from(SNAIL, SNAIL_KEY)
    tuck = move_region(out, 14, 7, 17, 10, 0, 2)    # stalks pull in: the eyes drop 2 px
    fwd = move_region(out, 14, 7, 17, 14, 1, 0)     # the head stretches forward 1 px
    for y in range(7, 15):
        if out.a[y][14] is not None:
            fwd.a[y][14] = out.a[y][14]
    return [out, tuck, fwd]


