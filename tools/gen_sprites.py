#!/usr/bin/env python3
"""Generate SCENE_DIR/sprites.js from the scene's Python art modules.

usage: gen_sprites.py SCENE_DIR

Each module in SCENE_DIR/art (listed in scene.json "art", else alphabetical) has
export() returning a list of
  ('sprite', name, [Grid frames], anchor_x, anchor_y)   -> def(name, key, rows)
  ('const', NAME, 'js literal')                         -> const NAME = ...;
Modules import artlib (tools/artlib.py) for Grid, stamping, shapes and previews.
Hand-writing def(...) calls straight into a .js file works too; this is for art
that is easier to build in code (organic shapes, variants, snow overlays).
"""
import importlib, json, os, pathlib, sys

KIT = pathlib.Path(__file__).resolve().parent.parent

def main(scene):
    scene = pathlib.Path(scene).resolve()
    os.environ['PIXEL_SCENE'] = str(scene)
    sys.path.insert(0, str(KIT / 'tools'))
    sys.path.insert(0, str(scene / 'art'))
    import artlib
    artlib.ROOT = scene
    m = json.loads((scene / 'scene.json').read_text())
    mods = m.get('art') or sorted(p.stem for p in (scene / 'art').glob('*.py'))
    parts = ['/* generated by pixel-loop tools/gen_sprites.py from art/*.py - pixel maps */\n']
    consts = {}
    for name in mods:
        mod = importlib.import_module(name)
        if not hasattr(mod, 'export'):
            continue
        for item in mod.export():
            if item[0] == 'sprite':
                _, sname, frames, ax, ay = item
                parts.append(artlib.to_js(sname, frames, ax, ay))
            elif item[0] == 'const':
                consts[item[1]] = item[2]
    for k, v in consts.items():
        parts.append('const %s = %s;\n' % (k, v))
    out = scene / 'sprites.js'
    out.write_text('\n'.join(parts))
    print('wrote', out, out.stat().st_size, 'bytes')

if __name__ == '__main__':
    main(sys.argv[1])
