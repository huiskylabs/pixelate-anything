ADV, LINE = 6, 8

def width(s):
    return max(0, len(s) * ADV - 1)

def draw(grid, s, x, y, slot, shadow=None):
    """draw text into anything with .set(x, y, v); shadow: a slot for a 1 px drop shadow"""
    for i, ch in enumerate(s):
        rows = GLYPHS.get(ch, GLYPHS['?']).split('|')
        for j, r in enumerate(rows):
            for k, c in enumerate(r):
                if c == '#':
                    if shadow is not None:
                        grid.set(x + i * ADV + k + 1, y + j + 1, shadow)
        for j, r in enumerate(rows):
            for k, c in enumerate(r):
                if c == '#':
                    grid.set(x + i * ADV + k, y + j, slot)

def draw_pil(img, s, x, y, rgb, shadow=None):
    px = img.load()
    W, H = img.size
    class G:
        def set(self, a, b, v):
            if 0 <= a < W and 0 <= b < H:
                px[a, b] = v
    draw(G(), s, x, y, rgb, shadow)
